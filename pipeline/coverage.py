"""Report how complete each enriched field is, per decade, so charts can state their gaps honestly."""
from collections import defaultdict

from common import NORMALIZED_FILE, REPORTS, ROOT, read_json

FILM_FIELDS = ["rating", "poster", "language", "countries", "budget", "revenue"]
PERSON_FIELDS = ["birthYear", "birthDate", "gender"]
ACTING_CATEGORIES = {"ACTOR IN A LEADING ROLE", "ACTRESS IN A LEADING ROLE", "ACTOR IN A SUPPORTING ROLE", "ACTRESS IN A SUPPORTING ROLE"}


def decade_of(year_text):
    return f"{int(year_text[:4]) // 10 * 10}s"


def is_filled(value):
    return value not in (None, [], "")


def coverage_table(items, fields, group_of):
    """One row per group: item count, then the percentage of items with each field filled."""
    groups = defaultdict(list)
    for item in items:
        groups[group_of(item)].append(item)

    rows = []
    for group in sorted(groups):
        members = groups[group]
        percents = [100 * sum(is_filled(member.get(field)) for member in members) / len(members) for field in fields]
        rows.append([group, len(members), *percents])
    total = [100 * sum(is_filled(item.get(field)) for item in items) / len(items) for field in fields]
    rows.append(["All", len(items), *total])
    return rows


def as_markdown(title, fields, rows):
    lines = [f"## {title}", "", f"| Group | Count | {' | '.join(fields)} |", f"|---|---:|{'---:|' * len(fields)}"]
    for group, count, *percents in rows:
        lines.append(f"| {group} | {count:,} | " + " | ".join(f"{percent:.0f}%" for percent in percents) + " |")
    return "\n".join(lines) + "\n"


def run():
    data = read_json(NORMALIZED_FILE)
    if not data.get("enriched"):
        print("  not enriched, skipping")
        return

    films = {film["id"]: film for film in data["films"]}
    people = {person["id"]: person for person in data["people"]}
    competitive = [nomination for nomination in data["nominations"] if nomination["competitive"]]

    def film_ids_in(categories):
        return {film["id"] for nomination in competitive if nomination["category"] in categories for film in nomination["films"]}

    def person_ids_in(categories):
        return {
            nominee["id"]
            for nomination in competitive
            if nomination["category"] in categories
            for nominee in nomination["nominees"]
            if nominee["type"] == "person"
        }

    nominated_films = [film for film in data["films"] if film["nominations"] > 0]
    nominated_people = [person for person in data["people"] if person["type"] == "person" and person["nominations"] > 0]
    best_picture = [films[film_id] for film_id in film_ids_in({"BEST PICTURE"})]
    acting = [people[person_id] for person_id in person_ids_in(ACTING_CATEGORIES)]

    def film_decade(film):
        return decade_of(film["filmYear"])

    def person_decade(person):
        start = person["firstCeremony"] // 10 * 10
        return f"Ceremonies {start:02d}-{start + 9:02d}"

    report = [
        "# Enrichment coverage",
        "",
        "Generated by `pipeline/coverage.py`. Percentages are the share of items with a value. Decades use the film year.",
        "",
        as_markdown("All nominated films", FILM_FIELDS, coverage_table(nominated_films, FILM_FIELDS, film_decade)),
        as_markdown("Best Picture nominees", FILM_FIELDS, coverage_table(best_picture, FILM_FIELDS, film_decade)),
        as_markdown("All nominated people, by first nomination", PERSON_FIELDS, coverage_table(nominated_people, PERSON_FIELDS, person_decade)),
        as_markdown("Acting nominees, by first nomination", PERSON_FIELDS, coverage_table(acting, PERSON_FIELDS, person_decade)),
    ]

    path = REPORTS / "coverage.md"
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(report), encoding="utf-8", newline="\n")
    print(f"  wrote {path.relative_to(ROOT)}")


if __name__ == "__main__":
    run()
