"""Test every hook planned for the story against the enriched data.

Writes analysis/story_claims.md. Run with: python analysis/story_claims.py
Standard library only. Anything the data doesn't support gets rewritten or dropped from the story.
"""
import sys
from collections import Counter, defaultdict
from pathlib import Path
from statistics import mean, median

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "pipeline"))

from common import NORMALIZED_FILE, read_json  # noqa: E402
from enrich import adjust_for_inflation, load_cpi  # noqa: E402

ERAS = [("1927-1949", 1927, 1949), ("1950-1969", 1950, 1969), ("1970-1989", 1970, 1989), ("1990-2009", 1990, 2009), ("2010-2025", 2010, 2025)]
LEAD_ACTING = {"ACTOR IN A LEADING ROLE": "man", "ACTRESS IN A LEADING ROLE": "woman"}
CRAFTS = {
    "Directing": {"DIRECTING"},
    "Writing": {"WRITING (Adapted Screenplay)", "WRITING (Original Screenplay)"},
    "Cinematography": {"CINEMATOGRAPHY", "CINEMATOGRAPHY (Black-and-White)", "CINEMATOGRAPHY (Color)"},
    "Film Editing": {"FILM EDITING"},
    "Original Score": {"MUSIC (Original Score)"},
    "Costume Design": {"COSTUME DESIGN", "COSTUME DESIGN (Black-and-White)", "COSTUME DESIGN (Color)"},
}
COMPANIONS = {
    "Directing": {"DIRECTING", "DIRECTING (Dramatic Picture)", "DIRECTING (Comedy Picture)"},
    "Film Editing": {"FILM EDITING"},
    "Any screenplay": {"WRITING (Adapted Screenplay)", "WRITING (Original Screenplay)", "WRITING (Original Story)"},
    "Any acting": {"ACTOR IN A LEADING ROLE", "ACTRESS IN A LEADING ROLE", "ACTOR IN A SUPPORTING ROLE", "ACTRESS IN A SUPPORTING ROLE"},
}
MIN_VOTES = 1000

data = read_json(NORMALIZED_FILE)
films = {film["id"]: film for film in data["films"]}
people = {person["id"]: person for person in data["people"]}
competitive = [nomination for nomination in data["nominations"] if nomination["competitive"]]
cpi = load_cpi()
lines = []


def film_year(nomination):
    return int(nomination["year"][:4])


def era_of(year):
    return next(name for name, start, end in ERAS if start <= year <= end)


def percent(part, whole):
    return f"{100 * part / whole:.0f}%" if whole else "n/a"


def heading(text):
    lines.extend(["", f"## {text}", ""])


def table(headers, rows):
    lines.append("| " + " | ".join(headers) + " |")
    lines.append("|" + "---|" * len(headers))
    lines.extend("| " + " | ".join(str(cell) for cell in row) + " |" for row in rows)
    lines.append("")


def by_ceremony(category):
    groups = defaultdict(list)
    for nomination in competitive:
        if nomination["category"] == category:
            groups[nomination["ceremony"]].append(nomination)
    return groups


best_picture = by_ceremony("BEST PICTURE")

lines.append("# Story claim tests")
lines.append("")
lines.append("Generated by `analysis/story_claims.py`. Competitive categories only. Eras use the film year.")

# Act I
heading("Act I: The Programme")
ceremonies = {ceremony["ceremony"]: ceremony for ceremony in data["ceremonies"]}
competitive_categories = [category for category in data["categories"] if category["competitive"]]
newest = max(competitive_categories, key=lambda category: category["firstCeremony"])
retired = [category for category in competitive_categories if category["lastCeremony"] < 98]
lines.append(f"- Categories at ceremony 1: {ceremonies[1]['competitiveCategories']}. At ceremony 98: {ceremonies[98]['competitiveCategories']}.")
peak = max(data["ceremonies"], key=lambda ceremony: ceremony["competitiveCategories"])
lines.append(f"- Most categories in one night: {peak['competitiveCategories']} at ceremony {peak['ceremony']}.")
lines.append(f"- Newest category: {newest['name']}, first at ceremony {newest['firstCeremony']}.")
lines.append(f"- Retired categories: {len(retired)} of {len(competitive_categories)}.")

# Act III
heading("Act III: The Formula")
winners_by_film = defaultdict(set)
for nomination in competitive:
    if nomination["winner"]:
        for film in nomination["films"]:
            winners_by_film[(nomination["ceremony"], film["id"])].add(nomination["category"])

rows = []
totals = Counter()
counted = 0
era_counts = defaultdict(Counter)
era_sizes = Counter()
for ceremony, nominations in sorted(best_picture.items()):
    winner = next(nomination for nomination in nominations if nomination["winner"])
    wins = set().union(*(winners_by_film[(ceremony, film["id"])] for film in winner["films"]))
    era = era_of(film_year(winner))
    era_sizes[era] += 1
    counted += 1
    for name, categories in COMPANIONS.items():
        if wins & categories:
            totals[name] += 1
            era_counts[era][name] += 1
for era, *_ in ERAS:
    rows.append([era, era_sizes[era], *[percent(era_counts[era][name], era_sizes[era]) for name in COMPANIONS]])
rows.append(["All", counted, *[f"{percent(totals[name], counted)} ({totals[name]})" for name in COMPANIONS]])
table(["Era", "Winners", *COMPANIONS], rows)

# How often the most-nominated film wins Best Picture
most_nominated_wins = Counter()
most_nominated_counted = Counter()
for ceremony, nominations in best_picture.items():
    counts = Counter()
    for nomination in competitive:
        if nomination["ceremony"] == ceremony:
            for film in nomination["films"]:
                counts[film["id"]] += 1
    entrants = {film["id"] for nomination in nominations for film in nomination["films"]}
    if len(entrants) < 2:
        continue  # Ceremony 2 announced no nominees, so there is no field to lead.
    top = max(counts[film_id] for film_id in entrants)
    leaders = {film_id for film_id in entrants if counts[film_id] == top}
    winner = {film["id"] for nomination in nominations if nomination["winner"] for film in nomination["films"]}
    era = era_of(film_year(nominations[0]))
    most_nominated_counted[era] += 1
    most_nominated_wins[era] += bool(leaders & winner)
lines.append("Most-nominated Best Picture entrant (ties count) also wins:")
lines.append("")
table(["Era", "Share"], [[era, f"{percent(most_nominated_wins[era], most_nominated_counted[era])} of {most_nominated_counted[era]}"] for era, *_ in ERAS])

# Act IV
heading("Act IV: The Money")
rows = []
winner_money = []
top_grosser_wins = Counter()
top_grosser_counted = Counter()
expected = defaultdict(list)
for ceremony, nominations in sorted(best_picture.items()):
    year = film_year(nominations[0])
    era = era_of(year)
    entrants = []
    for nomination in nominations:
        for film in nomination["films"]:
            full = films[film["id"]]
            adjusted = adjust_for_inflation(full.get("revenue"), year, cpi)
            entrants.append((film["id"], full["title"], adjusted, nomination["winner"]))
    known = [entrant for entrant in entrants if entrant[2] is not None]
    won = next((entrant for entrant in entrants if entrant[3]), None)
    if won and won[2] is not None:
        winner_money.append((year, won[1], won[2], era))
    # Only compare within a ceremony when every entrant's revenue is known.
    if len(known) == len(entrants) and won and len(entrants) > 1:
        top_grosser_counted[era] += 1
        expected[era].append(1 / len(entrants))
        top_grosser_wins[era] += max(entrants, key=lambda entrant: entrant[2])[0] == won[0]

for era, *_ in ERAS:
    values = [money for _, _, money, name in winner_money if name == era]
    rows.append([
        era,
        f"{len(values)} of {sum(1 for ceremony, n in best_picture.items() if era_of(film_year(n[0])) == era)}",
        f"${median(values) / 1e6:,.0f}M" if values else "n/a",
        f"{top_grosser_wins[era]} of {top_grosser_counted[era]}",
        f"{100 * mean(expected[era]):.0f}%" if expected[era] else "n/a",
    ])
table(["Era", "Winners with revenue", "Median winner revenue, 2025 dollars", "Top grosser won (fully known ceremonies)", "Chance rate"], rows)
lines.append("Revenue is lifetime gross, so re-releases of old films are adjusted as if earned in the release year. That overstates older films, so use eras and recent years, never single old films.")
lines.append("")
for label, start, end in (("1990-1999", 1990, 1999), ("2000-2009", 2000, 2009), ("2010-2019, before the pandemic", 2010, 2019), ("2020-2025", 2020, 2025)):
    values = [money for year, _, money, _ in winner_money if start <= year <= end]
    lines.append(f"- Median winner revenue, {label}: ${median(values) / 1e6:,.0f}M across {len(values)} winners.")
top_recent = []
for ceremony, nominations in sorted(best_picture.items()):
    year = film_year(nominations[0])
    if year < 2010:
        continue
    entrants = [(films[film["id"]].get("revenue"), film["title"], nomination["winner"]) for nomination in nominations for film in nomination["films"]]
    if all(revenue is not None for revenue, _, _ in entrants):
        top = max(entrants, key=lambda entrant: entrant[0])
        top_recent.append(f"{year}: {top[1]}{' (WON)' if top[2] else ''}")
lines.append("- Top grosser among nominees since 2010: " + "; ".join(top_recent) + ".")
ranked = sorted(winner_money, key=lambda entry: -entry[2])
lines.append("- Highest-earning winners, 2025 dollars: " + "; ".join(f"{title} ({year}) ${money / 1e9:.2f}B" for year, title, money, _ in ranked[:5]) + ".")
lines.append("- Lowest-earning winners, 2025 dollars: " + "; ".join(f"{title} ({year}) ${money / 1e6:.0f}M" for year, title, money, _ in ranked[-5:]) + ".")

# Act V
heading("Act V: The Audience Votes")


def audience_table(rating_of, votes_of, min_votes):
    rows = []
    overall = [0, 0, []]
    for era, *_ in ERAS:
        highest_wins = compared = 0
        chance = []
        winner_ratings, loser_ratings = [], []
        for ceremony, nominations in best_picture.items():
            if era_of(film_year(nominations[0])) != era:
                continue
            entrants = []
            for nomination in nominations:
                for film in nomination["films"]:
                    full = films[film["id"]]
                    if rating_of(full) is not None and (votes_of(full) or 0) >= min_votes:
                        entrants.append((rating_of(full), nomination["winner"]))
            total = sum(len(nomination["films"]) for nomination in nominations)
            if total < 2 or len(entrants) != total or not any(won for _, won in entrants):
                continue
            compared += 1
            chance.append(1 / len(entrants))
            best = max(rating for rating, _ in entrants)
            highest_wins += any(won and rating == best for rating, won in entrants)
            winner_ratings.extend(rating for rating, won in entrants if won)
            loser_ratings.extend(rating for rating, won in entrants if not won)
        overall[0] += highest_wins
        overall[1] += compared
        overall[2] += chance
        rows.append([
            era,
            compared,
            f"{highest_wins} ({percent(highest_wins, compared)})",
            f"{100 * mean(chance):.0f}%" if chance else "n/a",
            f"{mean(winner_ratings):.2f}" if winner_ratings else "n/a",
            f"{mean(loser_ratings):.2f}" if loser_ratings else "n/a",
        ])
    rows.append(["All", overall[1], f"{overall[0]} ({percent(overall[0], overall[1])})", f"{100 * mean(overall[2]):.0f}%", "", ""])
    table(["Era", "Ceremonies compared", "Highest-rated nominee won", "Chance rate", "Mean winner rating", "Mean other nominee rating"], rows)


for min_votes in (50, 200, 1000):
    lines.append(f"TMDb scores, every nominee at {min_votes}+ votes:")
    lines.append("")
    audience_table(lambda film: film.get("rating"), lambda film: film.get("votes"), min_votes)
lines.append(f"Private cross-check, IMDb scores at {MIN_VOTES}+ votes (never published):")
lines.append("")
audience_table(lambda film: film.get("private", {}).get("imdbRating"), lambda film: film.get("private", {}).get("imdbVotes"), MIN_VOTES)
lines.append("Scores are today's, not opinion at the time, and winning may itself lift a score.")

# Act VI
heading("Act VI: Who Gets the Gold")
ages = defaultdict(lambda: defaultdict(list))
unknown_age = Counter()
for nomination in competitive:
    gender = LEAD_ACTING.get(nomination["category"])
    if not gender or not nomination["winner"]:
        continue
    for nominee in nomination["nominees"]:
        birth = people[nominee["id"]].get("birthYear")
        if birth is None:
            unknown_age[gender] += 1
            continue
        ages[era_of(film_year(nomination))][gender].append((film_year(nomination) - birth, nominee["name"]))

rows = []
all_ages = defaultdict(list)
for era, *_ in ERAS:
    men = [age for age, _ in ages[era]["man"]]
    women = [age for age, _ in ages[era]["woman"]]
    all_ages["man"] += ages[era]["man"]
    all_ages["woman"] += ages[era]["woman"]
    rows.append([era, len(men), f"{mean(men):.1f}", f"{median(men):.0f}", len(women), f"{mean(women):.1f}", f"{median(women):.0f}", f"{mean(men) - mean(women):+.1f}"])
men = [age for age, _ in all_ages["man"]]
women = [age for age, _ in all_ages["woman"]]
rows.append(["All", len(men), f"{mean(men):.1f}", f"{median(men):.0f}", len(women), f"{mean(women):.1f}", f"{median(women):.0f}", f"{mean(men) - mean(women):+.1f}"])
table(["Era", "Best Actor wins", "Mean age", "Median", "Best Actress wins", "Mean age", "Median", "Gap (years)"], rows)
lines.append("Age is film year minus birth year, so it can be off by one. Unknown ages: " + str(dict(unknown_age)) + ".")
lines.append("")
lines.append("- Youngest and oldest Best Actor winners: " + str(min(all_ages["man"])) + ", " + str(max(all_ages["man"])) + ".")
lines.append("- Youngest and oldest Best Actress winners: " + str(min(all_ages["woman"])) + ", " + str(max(all_ages["woman"])) + ".")
lines.append("")

lines.append("Women's share of nominee credits with known gender:")
lines.append("")
rows = []
for craft, categories in CRAFTS.items():
    counts = defaultdict(Counter)
    for nomination in competitive:
        if nomination["category"] in categories:
            for nominee in nomination["nominees"]:
                if nominee["type"] == "person":
                    counts[era_of(film_year(nomination))][people[nominee["id"]].get("gender")] += 1
    cells = []
    known_total = unknown_total = 0
    for era, *_ in ERAS:
        known = counts[era]["man"] + counts[era]["woman"]
        known_total += known
        unknown_total += counts[era][None]
        cells.append(f"{percent(counts[era]['woman'], known)} ({counts[era]['woman']})")
    rows.append([craft, *cells, percent(unknown_total, known_total + unknown_total)])
table(["Craft", *[era for era, *_ in ERAS], "Credits with unknown gender"], rows)

directing_women = sorted(
    {(nomination["ceremony"], nominee["name"], nomination["winner"]) for nomination in competitive if nomination["category"] == "DIRECTING" for nominee in nomination["nominees"] if people[nominee["id"]].get("gender") == "woman"}
)
lines.append(f"- Women nominated for Best Director: {len(directing_women)} nominations. Winners: " + ", ".join(f"{name} (ceremony {ceremony})" for ceremony, name, won in directing_women if won) + ".")
lines.append("- First woman nominated for Best Director: " + str(directing_women[0][:2]) + ".")
lines.append("")

rows = []
non_english_winners = []
for era, *_ in ERAS:
    entrants = non_english = known = 0
    for ceremony, nominations in best_picture.items():
        if era_of(film_year(nominations[0])) != era:
            continue
        for nomination in nominations:
            for film in nomination["films"]:
                entrants += 1
                language = films[film["id"]].get("language")
                known += language is not None
                if language and language != "en":
                    non_english += 1
                    if nomination["winner"]:
                        non_english_winners.append(f"{film['title']} ({language}, ceremony {ceremony})")
    rows.append([era, entrants, f"{non_english} ({percent(non_english, known)})", percent(known, entrants)])
table(["Era", "Best Picture nominees", "Original language not English", "Language known"], rows)
lines.append("- Winners not originally in English: " + ", ".join(non_english_winners) + ".")

# Act VII
heading("Act VII: Snubbed")
nominated = [film for film in films.values() if film["nominations"] > 0]
lines.append(f"- Nominated films that won nothing: {sum(film['wins'] == 0 for film in nominated)} of {len(nominated)} ({percent(sum(film['wins'] == 0 for film in nominated), len(nominated))}).")
features = [film for film in nominated if film.get("private", {}).get("titleType") in ("movie", "tvMovie")]
lines.append(f"- Same, feature-type titles only: {sum(film['wins'] == 0 for film in features)} of {len(features)} ({percent(sum(film['wins'] == 0 for film in features), len(features))}).")
top_empty = sorted((film for film in nominated if film["wins"] == 0), key=lambda film: -film["nominations"])[:4]
lines.append("- Most nominations with no win: " + ", ".join(f"{film['title']} ({film['nominations']})" for film in top_empty) + ".")
ranked_people = [person for person in people.values() if person["type"] == "person"]
top_empty_people = sorted((person for person in ranked_people if person["wins"] == 0), key=lambda person: -person["nominations"])[:6]
lines.append("- Most-nominated people with no competitive win: " + ", ".join(f"{person['name']} ({person['nominations']}, {person['honors']} honors)" for person in top_empty_people) + ".")
top_people = sorted(ranked_people, key=lambda person: -person["nominations"])[:5]
lines.append("- Most-nominated people overall: " + ", ".join(f"{person['name']} ({person['nominations']} noms, {person['wins']} wins)" for person in top_people) + ".")
top_winners = sorted(ranked_people, key=lambda person: -person["wins"])[:5]
lines.append("- Most competitive wins: " + ", ".join(f"{person['name']} ({person['wins']} of {person['nominations']})" for person in top_winners) + ".")
lines.append("")

output = ROOT / "analysis" / "story_claims.md"
output.write_text("\n".join(lines), encoding="utf-8", newline="\n")
print(f"wrote {output.relative_to(ROOT)}")
